#!/usr/bin/env python3
"""Build a neutral example project from the bundled SimNIBS example subject.

    python docs/site/tools/make_demo_project.py
    python docs/site/tools/make_demo_project.py --demo /tmp/demo --data data/ernie

The example subject (``data/ernie``) is not tracked — a SimNIBS mesh and an
E-field library are several GB. When you have it, this script writes a project
whose paths contain no home directory, so it is safe to use in screenshots,
tutorials and bug reports.

It creates::

    <demo>/NP001/mesh/m2m_NP001/NP001.msh          -> <data>/mesh/m2m_ernie/ernie.msh
    <demo>/NP001/mesh/roi/midlayer_m1s1pmd/geo.hdf5 -> <data>/mesh/roi/...
    <demo>/NP001/efield/{search_positions,e}.hdf5  -> <data>/efield/...
    <demo>/NP001/coil_path/target_order.txt        (copy of the travel-sorted order)
    <demo>/coil/MagVenture_MCF-B65.ccd             (copy from SimNIBS)
    <demo>/emg_channels.yaml
    <demo>/NP001/NP001.yaml                        the project file to load

and prints the project path. The geometry is the real example head; nothing
here is synthetic.
"""

from __future__ import annotations

import argparse
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
DEFAULT_DATA = REPO / "data" / "ernie"
DEFAULT_DEMO = Path("/tmp/np_demo")


def build_demo_project(demo: Path = DEFAULT_DEMO,
                       data: Path = DEFAULT_DATA) -> Path:
    subject = demo / "NP001"
    for folder in (subject / "mesh" / "m2m_NP001",
                   subject / "mesh" / "roi" / "midlayer_m1s1pmd",
                   subject / "efield", subject / "coil_path",
                   subject / "results", demo / "coil"):
        folder.mkdir(parents=True, exist_ok=True)

    links = {
        subject / "mesh" / "m2m_NP001" / "NP001.msh":
            data / "mesh" / "m2m_ernie" / "ernie.msh",
        subject / "mesh" / "roi" / "midlayer_m1s1pmd" / "geo.hdf5":
            data / "mesh" / "roi" / "midlayer_m1s1pmd" / "geo.hdf5",
        subject / "efield" / "search_positions.hdf5":
            data / "efield" / "search_positions.hdf5",
        subject / "efield" / "e.hdf5": data / "efield" / "e.hdf5",
    }
    missing = [str(target) for target in links.values() if not target.is_file()]
    if missing:
        raise SystemExit("example dataset incomplete, missing:\n  " + "\n  ".join(missing))
    for link, target in links.items():
        if link.is_symlink() or link.exists():
            link.unlink()
        link.symlink_to(target)

    order = data / "coil_path" / "ernie_coil_algo_D-Optimal(RBF)_travel_sorted.txt"
    if not order.is_file():
        order = data / "coil_path" / "ernie_coil_algo_D-Optimal(RBF).txt"
    shutil.copyfile(order, subject / "coil_path" / "target_order.txt")

    emg = demo / "emg_channels.yaml"
    shutil.copyfile(data / "example_emg_channels.yaml", emg)

    coil = demo / "coil" / "MagVenture_MCF-B65.ccd"
    try:
        import simnibs
        source = (Path(simnibs.__file__).parent / "resources" / "coil_models"
                  / "Drakaki_BrainStim_2022" / "MagVenture_MCF-B65_new.ccd")
        shutil.copyfile(source, coil)
    except Exception:
        pass

    project = subject / "NP001.yaml"
    project.write_text(f"""\
# Example project generated by docs/site/tools/make_demo_project.py
project_name: NP001_M1_left
mesh_head_path: {subject}/mesh/m2m_NP001/NP001.msh
mesh_RIO_path: {subject}/mesh/roi/midlayer_m1s1pmd/geo.hdf5
coil_path: {coil}
targets_file: {subject}/efield/search_positions.hdf5
target_order_fn: {subject}/coil_path/target_order.txt
e_field_path: {subject}/efield/e.hdf5
emg_config_fn: {emg}
results_fn: {subject}/results/NP001_M1_left.csv
fit_fun: Linear
map_elms: 1
stimulator_amplitude: 42
stimulator_waveform: Biphasic
n_repetitions: 1
minium_isi: 4
default_speed: 40
tuning_speed: 10
efield_mode: Precomputed
""")
    return project


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--demo", default=str(DEFAULT_DEMO),
                        help="output folder (default: /tmp/np_demo)")
    parser.add_argument("--data", default=str(DEFAULT_DATA),
                        help="the example subject folder (default: data/ernie)")
    args = parser.parse_args(argv)
    project = build_demo_project(Path(args.demo), Path(args.data))
    print(f"example project: {project}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
